const NBSP = ' ';

// Короткие слова, которые не должны оставаться в конце строки
const SHORT_RU = /(^|[\s(«"„])([вксоуяиаВКСОУЯИА]|на|не|за|от|до|по|из|со|во|об|но|же|ли|бы|На|Не|За|От|До|По|Из|Со|Во|Об|Но) /g;

/** Неразрывные пробелы: перед тире, после коротких слов, между числом и единицей. */
export function typo(text: string): string {
  return text
    .replace(/ (—|–) /g, `${NBSP}$1 `)
    .replace(SHORT_RU, (_, pre: string, word: string) => `${pre}${word}${NBSP}`)
    .replace(/(\d) (?=[%$₽€]|[а-яёa-z])/gi, `$1${NBSP}`);
}
